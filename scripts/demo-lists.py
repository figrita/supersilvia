"""Write the "Lists" demo project: repeats whose copies differ, each by a list on the repeat.

    scripts/demo-lists.py [project folder] [--registry registry.json]

The folder defaults to "Lists" in the projects folder the app makes Untitled in, and is
replaced whole but for its renders/ and assets/. It borrows the Solids demo's Project and
Workspace (scripts/demo-solids.py), which check every cable, control and option against the
registry. Every Output is small, since every open tab's Output renders each frame.
"""

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("demo_solids", HERE / "demo-solids.py")
solids = importlib.util.module_from_spec(spec)
spec.loader.exec_module(solids)

SMALL = "480x270"
C = solids.C

# The Main Input's sound, generated by ffmpeg's lavfi so nothing is downloaded: a drum loop, a
# bass, a chord on a four-chord turn of 8 s, and an arpeggio, mixed and limited, mono.
TRACK = "assets/test-track.ogg"
_STEP = "pow(2,(if(lt(mod(t,8),2),0,if(lt(mod(t,8),4),3,if(lt(mod(t,8),6),5,-2))))/12)"
TRACK_COMMAND = [
    "ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
    "-f", "lavfi", "-i",
    "aevalsrc='0.9*sin(2*PI*(45*mod(t,0.5)+ (110/18)*(1-exp(-18*mod(t,0.5)))))*exp(-7*mod(t,0.5))':s=48000:d=16",
    "-f", "lavfi", "-i", "anoisesrc=d=16:c=white:r=48000:a=0.5",
    "-f", "lavfi", "-i", "anoisesrc=d=16:c=white:r=48000:a=0.5",
    "-f", "lavfi", "-i",
    f"aevalsrc='0.35*sin(2*PI*t*55*{_STEP})*(0.6+0.4*exp(-6*mod(t,0.25)))':s=48000:d=16",
    "-f", "lavfi", "-i",
    f"aevalsrc='0.12*(sin(2*PI*t*220*{_STEP})+sin(2*PI*t*277*{_STEP})+sin(2*PI*t*330*{_STEP}))':s=48000:d=16",
    "-f", "lavfi", "-i",
    "aevalsrc='0.18*sin(2*PI*t*440*pow(2,floor(mod(t*8,32))/6))*exp(-10*mod(t,0.125))':s=48000:d=16",
    "-filter_complex",
    "[1]highpass=f=1500,aeval='val(0)*exp(-22*mod(t-0.5,1))*if(lt(mod(t-0.5,1),0.3),1,0)':c=same[sn];"
    "[2]highpass=f=8000,aeval='val(0)*0.6*exp(-45*mod(t,0.25))':c=same[hh];"
    "[0][sn][hh][3][4][5]amix=inputs=6:normalize=0,alimiter=limit=0.9[out]",
    "-map", "[out]", "-ac", "1", "-c:a", "libvorbis", "-q:a", "5",
]


class Workspace(solids.Workspace):
    def layout(self):
        """demo-solids' layout of everything else, then the Main Input in a column of its own
        at the left, level with the first node it feeds, so the sound's path reads left to
        right."""
        node = next((n for n in self.nodes if n["slug"] == "maininput"), None)
        if node is None:
            return super().layout()
        at = self.nodes.index(node)
        del self.nodes[at]
        try:
            super().layout()
        finally:
            self.nodes.insert(at, node)
        shift = self.width_of(node) + 80
        for n in self.nodes:
            if n is not node and n["slug"] != "note":
                n["pos"]["x"] += shift
        fed = [c["to"]["node"] for c in self.connections if c["from"]["node"] == node["id"]]
        y = min((n["pos"]["y"] for n in self.nodes if n["id"] in fed), default=40.0)
        node["pos"] = {"x": 520.0, "y": y}


class Project(solids.Project):
    def workspace(self, name, blurb, kind="solids"):
        ws = Workspace(self, name, blurb, kind)
        self.workspaces.append(ws)
        return ws

    def write(self, root):
        """The project as demo-solids writes one, with the Main Input on the test track."""
        super().write(root)
        track = root / TRACK
        if not track.exists():
            subprocess.run(TRACK_COMMAND + [track.name], cwd=track.parent, check=True)
        manifest = root / "project.ssp"
        data = json.loads(manifest.read_text())
        data["main_input"] = {"audio": {"kind": "file", "asset": TRACK}, "monitor": 0.0}
        manifest.write_text(json.dumps(data, indent=2) + "\n")


def levels(ws, count, low=60.0, high=16000.0, rise=0.02, fall=0.25):
    """The Main Input's Spectrum gathered into `count` bands between `low` and `high` Hz and
    eased by a Lag: the list a spectrum analyzer's copies read."""
    source = ws.add("maininput", C[0], 900)
    bands = ws.add("bands", C[0], 1100, controls={"count": float(count), "low": low, "high": high})
    ws.cable(source, "spectrum", bands, "spectrum")
    lag = ws.add("lag", C[0], 1250, controls={"rise": rise, "fall": fall})
    ws.cable(bands, "bands", lag, "list")
    return lag


def show(ws, x, y, solid, master, controls=None):
    return ws.show(x, y, solid, master=master, sway=(0.06, 0.1), resolution=SMALL, controls=controls)


def bars(p):
    ws = p.workspace("Bars", "A row of boxes, each as tall as its item of a list")
    ws.note(
        40,
        40,
        "A Range of sixteen heights goes into the Repeat twice: into Count X, so there are as "
        "many boxes as items, and into Scale Y, so box i is as tall as item i. The box sits "
        "on the floor, so it grows upward. An Oscillator swings the Range's To, and every "
        "bar follows.\n\nTry: change the Range's Count; cable the Range into Turn as well.",
    )
    master = ws.master(C[0], 700)
    box = ws.shape("box", C[0], 40, width=0.32, height=1.0, depth=0.32, y=0.5, rounding=0.03, color="#e8925a")
    heights = ws.add("range", C[0], 400, controls={"count": 16.0, "from": 0.2, "to": 2.4})
    swing = ws.sway(C[0], 560, master, amplitude=0.8, offset=2.0)
    ws.cable(swing, "output", heights, "to")
    row = ws.mod("repeatgrid", C[1], 40, box, controls={"spacingX": 0.45, "spacingY": 0.0, "spacingZ": 0.0}, options={"extent": "counted", "perCopy": "on"})
    ws.cable(heights, "list", row, "countX")
    ws.cable(heights, "list", row, "copyScaleY")
    show(ws, C[2], 40, row, master, controls={"distance": 7.0, "tilt": 0.08})


