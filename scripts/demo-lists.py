def main():
    args = sys.argv[1:]
    registry = None
    if "--registry" in args:
        at = args.index("--registry")
        registry = args[at + 1]
        del args[at : at + 2]
    root = Path(args[0]).expanduser() if args else solids.documents() / "supersilvia" / "Lists"
    p = Project(solids.load_registry(registry))
    for build in (
        spectrum_bars,
        spectrum_spokes,
        spectrum_ring,
        spectrum_city,
        spectrum_planet,
        bars,
        city,
        stair,
        spikes,
        forever,
        stamp_points,
        tile_sizes,
    ):
        build(p)
    p.write(root)
    print(f"wrote {root}: {len(p.workspaces)} workspaces, {p._node} nodes")


if __name__ == "__main__":
    main()
